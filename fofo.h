void draw_image(uint32_t x, uint32_t y, uint32_t w, uint32_t h, const uint32_t *img_data) {
    for (uint32_t row = 0; row < h; row++) {
        for (uint32_t col = 0; col < w; col++) {
            uint32_t screen_x = x + col;
            uint32_t screen_y = y + row;

            // Bounds checking: prevent drawing outside the allocated screen buffer
            if (screen_x < fofo_width && screen_y < fofo_height) {
                uint32_t pixel_color = img_data[row * w + col];
                draw_pixel(screen_x, screen_y, pixel_color);
            }
        }
    }
}




