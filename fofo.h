int counter(void *data) {
    uint32_t *shared_timer = (uint32_t *)data;
    
    // As long as the window is open, this CPU room stays awake!
    while (fofo_running) {
        
        if (*shared_timer > 0) {
            fofo_delay(1);       // Wait 1 full second
            *shared_timer -= 1;  // Subtract 1
        } else {
            
            fofo_delay(0.01); 
        }
    }
    return 0;
}


